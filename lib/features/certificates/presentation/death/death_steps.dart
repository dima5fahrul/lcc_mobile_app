class DeathNotice extends StatelessWidget {
  const DeathNotice({
    super.key,
    required this.text,
    this.icon = 'info',
    this.amber = false,
  });

  final String text;
  final String icon;
  final bool amber;

  @override
  Widget build(BuildContext context) => Container(
        padding: const EdgeInsets.all(16),
        decoration: BoxDecoration(
          color: amber ? AppColors.warningSurface : AppColors.primarySoft,
          border: Border.all(
            // `border-amber-100` on both pages (Birth `:1511`, Death
            // `:1461`) = Tailwind v4 `oklch(96.2% 0.059 95.617)` =
            // `#FEF3C6` = `AppColors.warningTint`. **Not**
            // `warningOutline`, which is `amber-200` `#FEE685` and
            // belongs to HomePage's action banner (`:394`) — the only
            // `amber-200` in the whole of `src/`.
            color: amber ? AppColors.warningTint : AppColors.primarySoft,
          ),
          borderRadius: BorderRadius.circular(16),
        ),
        child: Row(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: <Widget>[
            LucideIcon(name: icon, size: 16),
            const SizedBox(width: 10),
            Expanded(
              child: Text(
                text,
                style: TextStyle(
                  fontSize: 12,
                  height: 1.5,
                  color: amber
                      ? AppColors.warning
                      : AppColors.primary,
                ),
              ),
            ),
          ],
        ),
      );
}

Widget _pair(Widget a, Widget b) => Row(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: <Widget>[
        Expanded(child: a),
        const SizedBox(width: 12),
        Expanded(child: b),
      ],
    );

