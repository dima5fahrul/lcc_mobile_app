/// `:1459-1513` — Step 6, **Review**. Five cards.
///
/// **Both** parent cards can collapse to a single `rowStatus` row (`:1487`,
/// `:1491`); Birth's only father card can. And `rowDateCause` carries the
/// `cause == "other" ? causeOther : labelOf(cause)` branch (`:1482`) —
/// `F2-AC-70`.
class DeathStep6 extends StatelessWidget {
  const DeathStep6({super.key, required this.cubit, required this.state});

  final DeathFormCubit cubit;
  final DeathFormViewState state;

  @override
  Widget build(BuildContext context) {
    final DeathFormData f = state.form;
    final DeathDeceasedInfo d = f.deceased;
    String dash() => deathT(context, 'dash');
    String join(Iterable<String> parts, String sep) {
      final List<String> kept =
          parts.where((String p) => p.isNotEmpty).toList();
      return kept.isEmpty ? dash() : kept.join(sep);
    }

    final String genderLabel = d.gender.isEmpty
        ? ''
        : deathTxtOf(
            context,
            kDeathGenders
                .firstWhere(
                  (DeathGenderOption g) => g.value == d.gender,
                  orElse: () => kDeathGenders.first,
                )
                .label,
          );

    return Column(
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: <Widget>[
        DeathNotice(
          text: deathT(context, 'reviewWarning'),
          icon: 'circle-alert',
          amber: true,
        ),
        _ReviewCard(
          title: deathT(context, 'step1Title'),
          rows: <(String, String)>[
            (
              deathT(context, 'rowProvinceDistrictVillage'),
              join(<String>[
                state.headerNames['province'] ?? '',
                state.headerNames['district'] ?? '',
                state.headerNames['village'] ?? '',
              ], ' / ')
            ),
            (deathT(context, 'documentNo'), state.draft?.referenceNo ?? dash()),
          ],
        ),
        _ReviewCard(
          title: deathT(context, 'step2Title'),
          rows: <(String, String)>[
            (
              deathT(context, 'rowName'),
              d.fullName.isEmpty ? dash() : d.fullName
            ),
            (
              deathT(context, 'rowGenderDob'),
              join(<String>[genderLabel, d.dob], ' · ')
            ),
            (
              deathT(context, 'rowPlaceOfDeath'),
              join(<String>[
                state.podNames['village'] ?? '',
                state.podNames['district'] ?? '',
                state.podNames['province'] ?? '',
              ], ', ')
            ),
            (
              deathT(context, 'rowDateCause'),
              join(<String>[
                d.dateOfDeath,
                d.cause == 'other'
                    ? d.causeOther
                    : cubit
                        .referenceStateOf(DeathRefList.cause)
                        .labelOf(d.cause),
              ], ' · ')
            ),
          ],
        ),
        _ReviewCard(
          title: deathT(context, 'step3Title'),
          rows: f.motherSkip
              ? <(String, String)>[
                  (
                    deathT(context, 'rowStatus'),
                    deathT(context, 'statusDeceasedUnknown')
                  ),
                ]
              : <(String, String)>[
                  (
                    deathT(context, 'rowName'),
                    f.mother.fullName.isEmpty ? dash() : f.mother.fullName
                  ),
                ],
        ),
        _ReviewCard(
          title: deathT(context, 'step4Title'),
          rows: f.fatherSkip
              ? <(String, String)>[
                  (
                    deathT(context, 'rowStatus'),
                    deathT(context, 'statusDeceasedUnknown')
                  ),
                ]
              : <(String, String)>[
                  (
                    deathT(context, 'rowName'),
                    f.father.fullName.isEmpty ? dash() : f.father.fullName
                  ),
                ],
        ),
        _ReviewCard(
          title: deathT(context, 'step5Title'),
          rows: <(String, String)>[
            (
              deathT(context, 'rowName'),
              f.informant.fullName.isEmpty ? dash() : f.informant.fullName
            ),
            (
              deathT(context, 'rowRelationship'),
              cubit
                      .referenceStateOf(DeathRefList.relation)
                      .labelOf(f.informant.relationship)
                      .isEmpty
                  ? dash()
                  : cubit
                      .referenceStateOf(DeathRefList.relation)
                      .labelOf(f.informant.relationship)
            ),
            (
              deathT(context, 'rowPhone'),
              f.informant.phone.isEmpty ? dash() : f.informant.phone
            ),
          ],
        ),
      ],
    );
  }
}

