/// `:1509-1571` — Step 6, **Review**. Five cards.
///
/// The step-4 card **collapses to a single `reviewStatus`/`reviewFatherUnknown`
/// row** when the father is unknown (`:1544-1545`); every other card keeps its
/// rows. `F2-AC-70`.
class BirthStep6 extends StatelessWidget {
  const BirthStep6({super.key, required this.cubit, required this.state});

  final BirthFormCubit cubit;
  final BirthFormViewState state;

  @override
  Widget build(BuildContext context) {
    final BirthFormData f = state.form;
    String empty() => birthT(context, 'emptyValue');
    String join(Iterable<String> parts, String sep) {
      final List<String> kept =
          parts.where((String p) => p.isNotEmpty).toList();
      return kept.isEmpty ? empty() : kept.join(sep);
    }

    final String genderLabel = f.child.gender.isEmpty
        ? ''
        : birthT(
            context,
            kBirthGenders
                .firstWhere(
                  (BirthGenderOption g) => g.value == f.child.gender,
                  orElse: () => kBirthGenders.first,
                )
                .labelKey,
          );

    return Column(
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: <Widget>[
        BirthNotice(
          text: birthT(context, 'reviewWarning'),
          icon: 'circle-alert',
          amber: true,
        ),
        _ReviewCard(
          title: birthT(context, 'step1Title'),
          rows: <(String, String)>[
            (
              birthT(context, 'reviewProvinceDistrictVillage'),
              join(<String>[
                state.headerNames['province'] ?? '',
                state.headerNames['district'] ?? '',
                state.headerNames['village'] ?? '',
              ], ' / ')
            ),
            (birthT(context, 'documentNo'), state.draft?.referenceNo ?? empty()),
          ],
        ),
        _ReviewCard(
          title: birthT(context, 'step2Title'),
          rows: <(String, String)>[
            (
              birthT(context, 'reviewName'),
              f.child.fullName.isEmpty ? empty() : f.child.fullName
            ),
            (
              birthT(context, 'reviewGenderDob'),
              join(<String>[genderLabel, f.child.dob], ' · ')
            ),
            (
              birthT(context, 'reviewBirth'),
              join(<String>[
                cubit
                    .referenceStateOf(BirthRefList.birthType)
                    .labelOf(f.child.birthType),
                f.child.birthOrder.isEmpty ? '' : '#${f.child.birthOrder}',
              ], ' · ')
            ),
            (
              birthT(context, 'reviewPlaceOfBirth'),
              join(<String>[
                state.pobNames['village'] ?? '',
                state.pobNames['district'] ?? '',
                state.pobNames['province'] ?? '',
              ], ', ')
            ),
          ],
        ),
        _ReviewCard(
          title: birthT(context, 'step3Title'),
          rows: <(String, String)>[
            (
              birthT(context, 'reviewName'),
              f.mother.fullName.isEmpty ? empty() : f.mother.fullName
            ),
            (
              birthT(context, 'reviewIdCensus'),
              f.mother.censusOrId.isEmpty ? empty() : f.mother.censusOrId
            ),
          ],
        ),
        _ReviewCard(
          title: birthT(context, 'step4Title'),
          rows: f.fatherUnknown
              ? <(String, String)>[
                  (
                    birthT(context, 'reviewStatus'),
                    birthT(context, 'reviewFatherUnknown')
                  ),
                ]
              : <(String, String)>[
                  (
                    birthT(context, 'reviewName'),
                    f.father.fullName.isEmpty ? empty() : f.father.fullName
                  ),
                  (
                    birthT(context, 'reviewIdCensus'),
                    f.father.censusOrId.isEmpty ? empty() : f.father.censusOrId
                  ),
                ],
        ),
        _ReviewCard(
          title: birthT(context, 'step5Title'),
          rows: <(String, String)>[
            (
              birthT(context, 'reviewName'),
              f.informant.fullName.isEmpty ? empty() : f.informant.fullName
            ),
            (
              birthT(context, 'reviewRelationship'),
              cubit
                      .referenceStateOf(BirthRefList.relation)
                      .labelOf(f.informant.relationship)
                      .isEmpty
                  ? empty()
                  : cubit
                      .referenceStateOf(BirthRefList.relation)
                      .labelOf(f.informant.relationship)
            ),
            (
              birthT(context, 'reviewPhone'),
              f.informant.phone.isEmpty ? empty() : f.informant.phone
