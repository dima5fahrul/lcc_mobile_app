/// `:1088-1096` etc. — the blue/amber notice cards.
class BirthNotice extends StatelessWidget {
  const BirthNotice({
    super.key,
    required this.text,
    this.icon = 'info',
    this.amber = false,
  });

  final String text;
  final String icon;
  final bool amber;

  @override
  Widget build(BuildContext context) => Container(
        padding: const EdgeInsets.all(16),
        decoration: BoxDecoration(
          color: amber ? AppColors.warningSurface : AppColors.primarySoft,
          border: Border.all(
            // `border-amber-100` on both pages (Birth `:1511`, Death
            // `:1461`) = Tailwind v4 `oklch(96.2% 0.059 95.617)` =
            // `#FEF3C6` = `AppColors.warningTint`. **Not**
