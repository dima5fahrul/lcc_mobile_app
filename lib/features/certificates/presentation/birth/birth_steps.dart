            color: amber ? AppColors.warningTint : AppColors.primarySoft,
          ),
          borderRadius: BorderRadius.circular(16),
        ),
        child: Row(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: <Widget>[
            LucideIcon(name: icon, size: 16),
            const SizedBox(width: 10),
            Expanded(
              child: Text(
                text,
                style: TextStyle(
                  fontSize: 12,
                  height: 1.5,
                  color: amber
                      ? AppColors.warning
                      : AppColors.primary,
                ),
              ),
            ),
          ],
        ),
      );
}

