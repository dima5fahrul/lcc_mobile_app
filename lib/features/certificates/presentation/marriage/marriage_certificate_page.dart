/// `:626-661` — the seven dots and their connectors.
class _StepIndicator extends StatelessWidget {
  const _StepIndicator({required this.step, required this.total});

  final int step;
  final int total;

  @override
  Widget build(BuildContext context) => Container(
        color: AppColors.white,
        padding: const EdgeInsets.symmetric(
          horizontal: AppSpacing.gap16,
          vertical: AppSpacing.gap16,
        ),
        child: Row(
          children: <Widget>[
            for (int id = 1; id <= total; id++) ...<Widget>[
              _Dot(id: id, done: step > id, active: step == id),
              if (id != total)
                Expanded(
                  child: Container(
                    height: 2,
                    margin: const EdgeInsets.symmetric(
                      horizontal: AppSpacing.gap6,
                    ),
                    color: step > id ? AppColors.primary : AppColors.gray200,
                  ),
                ),
            ],
          ],
        ),
      );
}

class _Dot extends StatelessWidget {
  const _Dot({required this.id, required this.done, required this.active});

  final int id;
  final bool done;
  final bool active;

  @override
  Widget build(BuildContext context) {
    final bool filled = done || active;
    return Opacity(
      // `:641` — a COMPLETED step is dimmed; the active one is not.
      opacity: done ? 0.55 : 1,
      child: Container(
        width: AppSpacing.gap32,
        height: AppSpacing.gap32,
        decoration: BoxDecoration(
          color: filled ? AppColors.primary : AppColors.gray100,
          shape: BoxShape.circle,
        ),
        child: Center(
          child: done
              ? const LucideIcon(
                  name: 'Check',
                  size: AppSpacing.gap14,
                  color: AppColors.white,
                )
              : Text(
                  '$id',
                  style: TextStyle(
                    fontSize: AppTypography.size12,
                    fontWeight: AppTypography.bold,
                    color: filled ? AppColors.white : AppColors.gray400Inline,
                  ),
                ),
        ),
      ),
    );
  }
}

