/// `MarriageCertificatePage` — the wizard shell, `:1084-1642`, plus the success
/// card at `:1032-1082`.
///
/// ## The CTA is NEVER disabled
///
/// `:1613-1637` renders one button whose only state change is `pending`.
/// Tapping it on an incomplete step flips `showErrors` and stays put
/// (`:1002-1006`). That is the whole validation gate, and a port that disabled
/// the button would hide every inline message the citizen needs to act on.
///
/// ## The page resolves nothing
///
/// It takes a [MarriageFormCubit] and a [CertificateFilePicker]. G-L5 forbids a
/// widget reading a locator; the route builder resolves the cubit and hands it
/// in, exactly as F1's Resident page does.
