String _t(BuildContext c, String key) => 'marriage.$key'.tr(context: c);

/// `formatLak(n, lang)` — the shared money formatter, as a parameter so the
/// page carries no formatting policy of its own.
typedef MarriageLakFormatter = String Function(int? amount);

class MarriageCertificatePage extends StatelessWidget {
  const MarriageCertificatePage({
    super.key,
    required this.cubit,
    required this.onBack,
    required this.formatLak,
    this.pickFile = pickCertificateFile,
  });

  final MarriageFormCubit cubit;
  final VoidCallback onBack;
  final MarriageLakFormatter formatLak;
  final CertificateFilePicker pickFile;

  @override
  Widget build(BuildContext context) {
    return BlocProvider<MarriageFormCubit>.value(
      value: cubit,
      child: BlocBuilder<MarriageFormCubit, MarriageFormViewState>(
        bloc: cubit,
        builder: (BuildContext context, MarriageFormViewState state) {
          if (state.submitted != null) {
            return _Success(
              state: state,
              onBack: onBack,
            );
          }
          return _Wizard(
            cubit: cubit,
            state: state,
            onBack: onBack,
            formatLak: formatLak,
            pickFile: pickFile,
          );
        },
      ),
    );
  }
}

class _Wizard extends StatelessWidget {
  const _Wizard({
    required this.cubit,
    required this.state,
    required this.onBack,
    required this.formatLak,
    required this.pickFile,
  });

  final MarriageFormCubit cubit;
  final MarriageFormViewState state;
  final VoidCallback onBack;
  final MarriageLakFormatter formatLak;
  final CertificateFilePicker pickFile;

  /// `:1028` — `caseRef || t("autoGenerated")`.
  String _documentNo(BuildContext context) =>
      state.caseRef.isNotEmpty ? state.caseRef : _t(context, 'autoGenerated');

  @override
  Widget build(BuildContext context) {
    return ValidationScope(
      showErrors: state.showErrors,
      serverErrors: state.serverErrors,
      // `:1004` — `scrollToFirstError()` after a refused advance or a 422.
      // The cubit cannot call it (no `BuildContext`), so it bumps a tick and
      // this listener performs the scroll. Same observable, and the cubit stays
      // free of the widget tree.
      child: BlocListener<MarriageFormCubit, MarriageFormViewState>(
        bloc: cubit,
        listenWhen: (MarriageFormViewState a, MarriageFormViewState b) =>
            a.scrollToErrorTick != b.scrollToErrorTick,
        listener: (BuildContext context, MarriageFormViewState _) =>
            scrollToFirstError(context),
        child: Scaffold(
          backgroundColor: AppColors.surface,
          body: SafeArea(
            child: Column(
              children: <Widget>[
                _SubHeader(
                  title: _t(context, 'title'),
                  subtitle: _t(context, 'subtitle'),
                  onBack: () {
                    // `:993-997` — back leaves the page only from step 1.
                    if (state.step > 1) {
                      cubit.goBack();
                    } else {
                      onBack();
                    }
                  },
                ),
                _StepIndicator(step: state.step, total: kMarriageStepCount),
                Expanded(
                  child: SingleChildScrollView(
                    padding: const EdgeInsets.fromLTRB(
                      AppSpacing.gap16,
                      AppSpacing.gap24,
                      AppSpacing.gap16,
                      AppSpacing.gap32,
                    ),
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: <Widget>[
                        _StepHeader(step: state.step),
                        const SizedBox(height: AppSpacing.gap12),
                        // `:1115-1133` — the 422 list, then the bare error.
                        // The two are mutually exclusive: the banner only shows
                        // when there are NO field messages (`:1128`).
                        if (state.serverErrors.isNotEmpty)
                          _ServerErrorList(
                            title: marriageSay(context, 'fixTitle'),
                            messages: state.serverErrors.values.toList(),
                          )
                        else if (state.submitError != null)
                          MarriageNote(
                            text: state.submitError!,
                            tone: MarriageNoteTone.red,
                            icon: 'AlertCircle',
                          ),
                        if (state.serverErrors.isNotEmpty ||
                            state.submitError != null)
                          const SizedBox(height: AppSpacing.gap20),
                        _body(context),
                      ],
                    ),
                  ),
                ),
                _Cta(
                  pending: state.submitPending,
                  label: state.submitPending
                      ? _t(context, 'submitting')
                      : state.step == kMarriageStepCount
                          ? 'marriage.pay'.tr(
                              context: context,
                              namedArgs: <String, String>{
                                'amount': formatLak(state.quote.data?.feeLak),
                              },
                            )
                          : _t(context, 'continue'),
                  onTap: () => cubit.next(),
                ),
              ],
            ),
          ),
        ),
      ),
    );
  }

  Widget _body(BuildContext context) {
    switch (state.step) {
      case 1:
        return MarriageStep1(
          state: state,
          onModeChosen: cubit.setBetrothalMode,
          onReset: cubit.resetBetrothal,
          onSearchChanged: cubit.setRecordSearch,
          onPickRecord: cubit.selectExisting,
          onUnlink: cubit.unlinkRecord,
          onHeaderChanged: cubit.setHeader,
          onBetrothalChanged: (MarriageBetrothal b) =>
              cubit.patchBetrothal((_) => b),
        );
      case 2:
        return MarriageSpouseStep(
          intro: _t(context, 'spouseAIntro'),
          section: MarriageSpouseSection(
            value: state.form.spouseA,
            onChanged: (MarriageSpouseInfo s) => cubit.patchSpouseA((_) => s),
            prevMarried: state.form.prevMarriedA,
            onTogglePrevMarried: cubit.togglePrevMarriedA,
            refs: _refs,
            serverErrors: state.serverErrors,
            provinces: state.provinces,
            cascade: state.cascade(MarriageCascade.spouseA),
            onAddressChanged: (v) =>
                cubit.patchSpouseA((MarriageSpouseInfo s) => s.copyWith(address: v)),
            pickFile: pickFile,
          ),
        );
      case 3:
        return MarriageSpouseStep(
          intro: _t(context, 'spouseBIntro'),
          section: MarriageSpouseSection(
            value: state.form.spouseB,
            onChanged: (MarriageSpouseInfo s) => cubit.patchSpouseB((_) => s),
            prevMarried: state.form.prevMarriedB,
            onTogglePrevMarried: cubit.togglePrevMarriedB,
            refs: _refs,
            serverErrors: state.serverErrors,
            provinces: state.provinces,
            cascade: state.cascade(MarriageCascade.spouseB),
            onAddressChanged: (v) =>
                cubit.patchSpouseB((MarriageSpouseInfo s) => s.copyWith(address: v)),
            pickFile: pickFile,
          ),
        );
      case 4:
        return MarriageStep4(
          form: state.form,
          pickFile: pickFile,
          onHouseholdBook: cubit.setHouseholdBook,
          onPhotos: cubit.setPhotos,
          onToggleChildren: cubit.toggleHasChildren,
          onBirthRecord: cubit.setBirthRecord,
        );
      case 5:
        return MarriageStep5(
          reg: state.form.reg,
          serverErrors: state.serverErrors,
          onChanged: (MarriageRegistration r) => cubit.patchReg((_) => r),
        );
      case 6:
        return MarriageStep6(
          state: state,
          documentNo: _documentNo(context),
          formatLak: formatLak,
        );
      case 7:
        return MarriageStep7(
          state: state,
          documentNo: _documentNo(context),
          onChanged: (p) => cubit.patchPayment((_) => p),
        );
      default:
        // Unreachable: `step` only ever moves through 1..7. Rendering nothing
        // rather than a placeholder panel, for the same reason Divorce's
        // terminal code renders nothing (§ 6.7).
        return const SizedBox.shrink();
    }
  }

  MarriageSpouseRefs get _refs => MarriageSpouseRefs(
        nationalities: state.nationalities,
        ethnicities: state.ethnicities,
        ethnicGroups: state.ethnicGroups,
        religions: state.religions,
      );
}

