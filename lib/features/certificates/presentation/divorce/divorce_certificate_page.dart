/// Six steps, not Marriage's seven, and the CTA is likewise never disabled.
/// The two pages are two independent transcriptions of two similar shells;
/// § 6.5's reasoning about `spousePayload` applies to the shells as well — a
/// shared one would need a flag for every difference, and there are several
