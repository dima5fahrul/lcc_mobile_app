String _t(BuildContext c, String key) => 'divorce.$key'.tr(context: c);

typedef DivorceLakFormatter = String Function(int? amount);

class DivorceCertificatePage extends StatelessWidget {
  const DivorceCertificatePage({
    super.key,
    required this.cubit,
    required this.onBack,
    required this.formatLak,
    this.pickFile = pickCertificateFile,
  });

  final DivorceFormCubit cubit;
  final VoidCallback onBack;
  final DivorceLakFormatter formatLak;
  final CertificateFilePicker pickFile;

  @override
  Widget build(BuildContext context) {
    return BlocProvider<DivorceFormCubit>.value(
      value: cubit,
      child: BlocBuilder<DivorceFormCubit, DivorceFormViewState>(
        bloc: cubit,
        builder: (BuildContext context, DivorceFormViewState state) {
          if (state.submitted != null) {
            return _Success(state: state, onBack: onBack);
          }
          return _Wizard(
            cubit: cubit,
            state: state,
            onBack: onBack,
            formatLak: formatLak,
            pickFile: pickFile,
          );
        },
      ),
    );
  }
}

class _Wizard extends StatelessWidget {
  const _Wizard({
    required this.cubit,
    required this.state,
    required this.onBack,
    required this.formatLak,
    required this.pickFile,
  });

  final DivorceFormCubit cubit;
  final DivorceFormViewState state;
  final VoidCallback onBack;
  final DivorceLakFormatter formatLak;
  final CertificateFilePicker pickFile;

  /// `:924` — `caseRef || t("autoGenerated")`.
  String _documentNo(BuildContext context) =>
      state.caseRef.isNotEmpty ? state.caseRef : _t(context, 'autoGenerated');

  @override
  Widget build(BuildContext context) {
    return ValidationScope(
      showErrors: state.showErrors,
      serverErrors: state.serverErrors,
      child: BlocListener<DivorceFormCubit, DivorceFormViewState>(
        bloc: cubit,
        listenWhen: (DivorceFormViewState a, DivorceFormViewState b) =>
            a.scrollToErrorTick != b.scrollToErrorTick,
        listener: (BuildContext context, DivorceFormViewState _) =>
            scrollToFirstError(context),
        child: Scaffold(
          backgroundColor: AppColors.surface,
          body: SafeArea(
            child: Column(
              children: <Widget>[
                _SubHeader(
                  title: _t(context, 'title'),
                  subtitle: _t(context, 'subtitle'),
                  onBack: () {
                    if (state.step > 1) {
                      cubit.goBack();
                    } else {
                      onBack();
                    }
                  },
                ),
                _StepIndicator(step: state.step, total: kDivorceStepCount),
                Expanded(
                  child: SingleChildScrollView(
                    padding: const EdgeInsets.fromLTRB(
                      AppSpacing.gap16,
                      AppSpacing.gap24,
                      AppSpacing.gap16,
                      AppSpacing.gap32,
                    ),
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: <Widget>[
                        _StepHeader(step: state.step),
                        const SizedBox(height: AppSpacing.gap12),
                        if (state.serverErrors.isNotEmpty)
                          _ServerErrorList(
                            title: divorceSay(context, 'fixTitle'),
                            messages: state.serverErrors.values.toList(),
                          )
                        else if (state.submitError != null)
                          DivorceNote(
                            text: state.submitError!,
                            tone: DivorceNoteTone.red,
                            icon: 'AlertCircle',
                          ),
                        if (state.serverErrors.isNotEmpty ||
                            state.submitError != null)
                          const SizedBox(height: AppSpacing.gap20),
                        _body(context),
                      ],
                    ),
                  ),
                ),
                _Cta(
                  pending: state.submitPending,
                  label: state.submitPending
                      ? _t(context, 'submitting')
                      : state.step == kDivorceStepCount
                          ? 'divorce.pay'.tr(
                              context: context,
                              namedArgs: <String, String>{
                                'amount': formatLak(state.quote.data?.feeLak),
                              },
                            )
                          : _t(context, 'continue'),
                  onTap: () => cubit.next(),
                ),
              ],
            ),
          ),
        ),
      ),
    );
  }

  Widget _body(BuildContext context) {
    switch (state.step) {
      case 1:
        return DivorceStep1(
          state: state,
          onTypeChanged: cubit.setDivorceType,
          onModeChosen: cubit.setMediationMode,
          onReset: cubit.resetMediation,
          onSearchChanged: cubit.setRecordSearch,
          onPickRecord: cubit.selectExisting,
          onUnlink: cubit.unlinkRecord,
          onHeaderChanged: cubit.setHeader,
          onMediationChanged: (DivorceMediation m) =>
              cubit.patchMediation((_) => m),
          onCourtChanged: (DivorceCourt c) => cubit.patchCourt((_) => c),
          onChildrenChanged: (DivorceChildren c) =>
              cubit.patchChildren((_) => c),
          onToggleChildren: cubit.toggleHasChildren,
          onCourtDecision: cubit.setCourtDecision,
          pickFile: pickFile,
        );
      case 2:
        return DivorceSpouseStep(
          intro: _t(context, 'husbandIntro'),
          section: DivorceSpouseSection(
            value: state.form.husband,
            onChanged: (DivorceSpouseInfo s) => cubit.patchHusband((_) => s),
            nationalities: state.nationalities,
            serverErrors: state.serverErrors,
            provinces: state.provinces,
            cascade: state.cascade(DivorceCascade.husband),
            onAddressChanged: (v) => cubit
                .patchHusband((DivorceSpouseInfo s) => s.copyWith(address: v)),
            pickFile: pickFile,
          ),
        );
      case 3:
        return DivorceSpouseStep(
          intro: _t(context, 'wifeIntro'),
          section: DivorceSpouseSection(
            value: state.form.wife,
            onChanged: (DivorceSpouseInfo s) => cubit.patchWife((_) => s),
            nationalities: state.nationalities,
            serverErrors: state.serverErrors,
            provinces: state.provinces,
            cascade: state.cascade(DivorceCascade.wife),
            onAddressChanged: (v) => cubit
                .patchWife((DivorceSpouseInfo s) => s.copyWith(address: v)),
            pickFile: pickFile,
          ),
        );
      case 4:
        return DivorceStep4(
          state: state,
          onBasisChanged: (DivorceBasis b) => cubit.patchBasis((_) => b),
          onHouseholdBook: cubit.setHouseholdBook,
          onGuaranteeCert: cubit.setGuaranteeCert,
          onPhotos: cubit.setPhotos,
          pickFile: pickFile,
        );
      case 5:
        return DivorceStep5(state: state, documentNo: _documentNo(context));
      case 6:
        return DivorceStep6(
          state: state,
          documentNo: _documentNo(context),
          onChanged: (p) => cubit.patchPayment((_) => p),
        );
      default:
        return const SizedBox.shrink();
    }
  }
}

